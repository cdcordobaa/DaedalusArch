// Builds experiments/v1.3-operators-hexddd/specs/<id>.yaml from arch/<id>.yaml (the architecture block, written by
// the rule in Docs/v1.3/operator-catalogue-hexddd.md §5) and the fitness_functions/scoring of presets/<style>.yaml,
// copied verbatim. Usage (repository root): node experiments/v1.3-operators-hexddd/build-specs.mjs
import * as fs from 'node:fs';
import * as path from 'node:path';
const here = path.dirname(new URL(import.meta.url).pathname);
fs.mkdirSync(path.join(here, 'specs'), { recursive: true });
for (const f of fs.readdirSync(path.join(here, 'arch')).sort()) {
  const arch = fs.readFileSync(path.join(here, 'arch', f), 'utf8');
  const style = /style:\s*(\S+)/.exec(arch)[1];
  const preset = fs.readFileSync(path.join(here, '../../presets', `${style}.yaml`), 'utf8');
  const i = preset.indexOf('\nfitness_functions:');
  const out = `# v1.3 operators-hexddd real-project spec (development data). Architecture block: arch/${f}.\n# Functions and scoring: verbatim from presets/${style}.yaml. Generated by build-specs.mjs; do not edit.\n\nspec_version: "1.0.0"\n\n${arch.trimEnd()}\n${preset.slice(i)}`;
  fs.writeFileSync(path.join(here, 'specs', f), out);
  console.log(f, style);
}
