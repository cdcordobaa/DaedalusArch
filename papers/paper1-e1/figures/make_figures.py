#!/usr/bin/env python3
"""Generate the pgfplots figures of paper 1 (E1) from committed CSVs only.

Run from the repository root:

    python3 papers/paper1-e1/figures/make_figures.py

Inputs (committed, read-only):
    results/e1-grid/agg/so5_grid.csv               per-cell AHS, file counts, status
    results/e1-grid/agg-size/size_functions.csv     per-function firing rates by spec level

Outputs (written next to this script):
    fig-ahs-by-level.tex     AHS per valid cell by spec level and generator model
    fig-firing.tex           share of valid Claude cells in which each function fires
    fig-files-ahs.tex        file count against AHS per valid Claude cell

Standard library only; the output is deterministic (no randomness, fixed jitter).
Markers differ by series as well as colour (Okabe-Ito palette), so identity never rests on colour alone.
"""

import csv
import os
import statistics

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
OUT = os.path.dirname(os.path.abspath(__file__))
GRID = os.path.join(ROOT, "results/e1-grid/agg/so5_grid.csv")
FUNCS = os.path.join(ROOT, "results/e1-grid/agg-size/size_functions.csv")

LEVELS = ["none", "minimal-prose", "full-aac"]
MODELS = [  # (model id, label, colour, marker)
    ("claude-haiku-4-5", "Haiku 4.5", "oiBlue", "*"),
    ("claude-sonnet-5-5", "Sonnet 5.5", "oiOrange", "square*"),
    ("claude-opus-5-5", "Opus 5.5", "oiGreen", "triangle*"),
    ("gpt-5.6-terra", "GPT-5.6-terra (Codex, expl.)", "oiPink", "diamond*"),
]
COLOURS = r"""\definecolor{oiBlue}{HTML}{0072B2}
\definecolor{oiOrange}{HTML}{E69F00}
\definecolor{oiGreen}{HTML}{009E73}
\definecolor{oiPink}{HTML}{CC79A7}
"""
HEADER = "% Generated by papers/paper1-e1/figures/make_figures.py from {src}. Do not edit by hand.\n"


def read(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def accepted(rows):
    return [r for r in rows if r["status"] == "accepted"]


def fig_ahs_by_level(rows):
    offsets = [-0.27, -0.09, 0.09, 0.27]
    jit = [-0.035, 0.0, 0.035]
    lines = [HEADER.format(src="results/e1-grid/agg/so5_grid.csv"), COLOURS]
    lines.append(r"""\begin{tikzpicture}
\begin{axis}[width=\linewidth, height=4.9cm, ymin=0.84, ymax=1.0, xmin=-0.5, xmax=2.5,
  xtick={0,1,2}, xticklabels={none, minimal-prose, full-aac}, ylabel={$\mathrm{AHS}_{\mathrm{comb}}$},
  ytick={0.85,0.90,0.95,1.00}, yticklabel style={/pgf/number format/fixed,/pgf/number format/precision=2},
  grid=major, grid style={gray!20}, axis line style={gray!60}, tick style={gray!60},
  legend style={font=\scriptsize, at={(0.5,1.02)}, anchor=south, legend columns=4, draw=none},
  every axis plot/.append style={only marks}]
""")
    for mi, (mid, label, col, mark) in enumerate(MODELS):
        pts, means = [], []
        for li, lev in enumerate(LEVELS):
            cell = [r for r in rows if r["requested_model_id"] == mid and r["spec_level"] == lev]
            cell.sort(key=lambda r: (r["task_id"], int(r["run_index"])))
            for k, r in enumerate(cell):
                x = li + offsets[mi] + jit[k % 3]
                pts.append(f"({x:.3f},{float(r['ahs_combined']):.3f})")
            if cell:
                means.append(f"({li + offsets[mi]:.3f},{statistics.mean(float(r['ahs_combined']) for r in cell):.4f})")
        lines.append(f"\\addplot[mark={mark}, mark size=1.3pt, draw={col}, fill={col}, fill opacity=0.35, draw opacity=0.6, forget plot]\n"
                     f"  coordinates {{{' '.join(pts)}}};\n")
        lines.append(f"\\addplot[mark={mark}, mark size=3pt, draw=black, fill={col}, line width=0.4pt]\n"
                     f"  coordinates {{{' '.join(means)}}};\n\\addlegendentry{{{label}}}\n")
    lines.append(r"""\draw[gray!70, dashed] (axis cs:-0.5,0.80) -- (axis cs:2.5,0.80);
\end{axis}
\end{tikzpicture}
""")
    return "".join(lines)


def fig_firing(funcs):
    fns = [("FF-C02", "C02 fan-out"), ("FF-P02", "P02 dep. inversion"), ("FF-C06", "C06 abstraction"),
           ("FF-C03", "C03 instability"), ("FF-CV05", "CV05 test pairing")]
    lev_style = [("none", "oiBlue", "north east lines"), ("minimal-prose", "oiOrange", "none"),
                 ("full-aac", "oiGreen", "crosshatch")]
    lines = [HEADER.format(src="results/e1-grid/agg-size/size_functions.csv"), COLOURS]
    lines.append(r"""\begin{tikzpicture}
\begin{axis}[width=\linewidth, height=5.0cm, ybar, bar width=4pt, ymin=0, ymax=1.08,
  symbolic x coords={""" + ",".join(f for f, _ in fns) + r"""}, xtick=data,
  xticklabels={""" + ",".join(f"{{{lab}}}" for _, lab in fns) + r"""}, xticklabel style={font=\tiny, align=center, text width=1.1cm},
  ylabel={share of cells that fire}, ytick={0,0.25,0.5,0.75,1},
  grid=major, ymajorgrids=true, xmajorgrids=false, grid style={gray!20}, axis line style={gray!60},
  legend style={font=\scriptsize, at={(0.5,1.02)}, anchor=south, legend columns=3, draw=none}]
""")
    for lev, col, pat in lev_style:
        coords = []
        for f, _ in fns:
            row = [r for r in funcs if r["arm"] == "claude" and r["spec_level"] == lev and r["function_id"] == f][0]
            coords.append(f"({f},{float(row['fire_rate']):.4f})")
        patt = "" if pat == "none" else f", postaction={{pattern={pat}, pattern color=white}}"
        lines.append(f"\\addplot[fill={col}, draw=none{patt}] coordinates {{{' '.join(coords)}}};\n"
                     f"\\addlegendentry{{{lev}}}\n")
    lines.append("\\end{axis}\n\\end{tikzpicture}\n")
    return "".join(lines)


def fig_files_ahs(rows):
    lev_style = [("none", "oiBlue", "*"), ("minimal-prose", "oiOrange", "square*"), ("full-aac", "oiGreen", "triangle*")]
    lines = [HEADER.format(src="results/e1-grid/agg/so5_grid.csv"), COLOURS]
    lines.append(r"""\begin{tikzpicture}
\begin{axis}[width=\linewidth, height=5.0cm, xlabel={\texttt{.ts} files under \texttt{src/}}, ylabel={$\mathrm{AHS}_{\mathrm{comb}}$},
  ymin=0.84, ymax=1.0, xmin=0, ytick={0.85,0.90,0.95,1.00},
  yticklabel style={/pgf/number format/fixed,/pgf/number format/precision=2},
  grid=major, grid style={gray!20}, axis line style={gray!60},
  legend style={font=\scriptsize, at={(0.5,1.02)}, anchor=south, legend columns=3, draw=none},
  every axis plot/.append style={only marks}]
""")
    for lev, col, mark in lev_style:
        cell = [r for r in rows if r["spec_level"] == lev and not r["requested_model_id"].startswith("gpt")]
        cell.sort(key=lambda r: (r["requested_model_id"], r["task_id"], int(r["run_index"])))
        pts = " ".join(f"({int(r['file_count'])},{float(r['ahs_combined']):.3f})" for r in cell)
        lines.append(f"\\addplot[mark={mark}, mark size=1.8pt, draw={col}, fill={col}, fill opacity=0.6] coordinates {{{pts}}};\n"
                     f"\\addlegendentry{{{lev}}}\n")
    lines.append("\\end{axis}\n\\end{tikzpicture}\n")
    return "".join(lines)


def main():
    rows = accepted(read(GRID))
    funcs = read(FUNCS)
    outputs = {
        "fig-ahs-by-level.tex": fig_ahs_by_level(rows),
        "fig-firing.tex": fig_firing(funcs),
        "fig-files-ahs.tex": fig_files_ahs(rows),
    }
    for name, text in outputs.items():
        with open(os.path.join(OUT, name), "w") as f:
            f.write(text)
        print("wrote", os.path.relpath(os.path.join(OUT, name), ROOT))


if __name__ == "__main__":
    main()
