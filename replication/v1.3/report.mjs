#!/usr/bin/env node
// Builds the per-number tables of Docs/v1.3/replication-2.md from the JSON rows of a full run:
//   node replication/v1.3/run.mjs --json rows.json
//   node replication/v1.3/report.mjs rows.json [--dir Docs/v1.3/replication-2] > tables.md
// stdout: the per-doc tally, then one table of every number that is not "yes" (mismatches and numbers not run).
// --dir: also writes the full table of one doc (every number, rows by line) to <dir>/<doc basename>.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';

const rows = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const md = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ').replace(/`/g, '\\`').replace(/</g, '&lt;');
// Code span for text that may itself contain backticks (GFM: no backslash escapes inside code spans).
const code = (s) => { const t = String(s).replace(/\|/g, '\\|').replace(/\n/g, ' '); return t.includes('`') ? `\`\` ${t} \`\`` : `\`${t}\``; };
const rep = (s) => ({ PASS: 'yes', FAIL: 'no', KNOWN: 'no', ERROR: 'error', skipped: 'not run' }[s] ?? s);
const docs = [...new Set(rows.map((r) => r.doc))].sort((a, b) => {
  const k = (d) => (d.includes('DiagnosticRuns') ? 0 : 1);
  return k(a) - k(b) || a.localeCompare(b);
});
const tally = (rs) => {
  const c = (f) => rs.filter(f).length;
  return { n: rs.length, yes: c((r) => r.status === 'PASS'), no: c((r) => r.status === 'FAIL' || r.status === 'KNOWN'),
    llm: c((r) => r.status === 'needs-LLM'), neo: c((r) => r.status === 'needs-Neo4j'), ext: c((r) => r.status === 'needs-external'),
    nc: c((r) => r.status === 'not-checkable'), err: c((r) => r.status === 'ERROR' || r.status === 'skipped') };
};
const args = process.argv.slice(3);
const dir = args.includes('--dir') ? args[args.indexOf('--dir') + 1] : undefined;
const row = (r) => {
  const diff = r.status === 'PASS' ? '—'
    : (r.status === 'FAIL' || r.status === 'KNOWN') ? `**reproduced ${md(r.actual)}**${r.note ? `. ${md(r.note)}` : ''}`
      : md(r.note);
  return `| ${md(r.what)}: “${md(r.stated)}” <sub>${r.id}</sub> | \`${r.doc.replace(/^Docs\//, '')}:${r.line}\` | ${r.command ? code(r.command) : ''} | ${rep(r.status)} | ${diff} |`;
};
const HEAD = ['| number (as stated) | doc file:line | command | reproduced | difference |', '|---|---|---|---|---|'];
const byLine = (a, b) => a.line - b.line || a.id.localeCompare(b.id);
const out = [];
out.push('| Doc | Numbers | yes | no | needs-LLM | needs-Neo4j | needs-external | not-checkable | error / not run |', '|---|---:|---:|---:|---:|---:|---:|---:|---:|');
for (const d of docs) {
  const t = tally(rows.filter((r) => r.doc === d));
  out.push(`| \`${d.replace(/^Docs\//, '')}\` | ${t.n} | ${t.yes} | ${t.no} | ${t.llm} | ${t.neo} | ${t.ext} | ${t.nc} | ${t.err} |`);
}
const T = tally(rows);
out.push(`| **Total** | **${T.n}** | **${T.yes}** | **${T.no}** | **${T.llm}** | **${T.neo}** | **${T.ext}** | **${T.nc}** | **${T.err}** |`, '');
for (const d of docs) {
  const rs = rows.filter((x) => x.doc === d).sort(byLine);
  const nonYes = rs.filter((r) => r.status !== 'PASS');
  if (nonYes.length) out.push(`### \`${d}\``, '', ...HEAD, ...nonYes.map(row), '');
  if (dir) {
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, basename(d)), `# Replication 2: every number in \`${d}\`\n\nGenerated by \`node replication/v1.3/report.mjs\` from a full \`npm run replicate:v1.3\` run; see [\`../replication-2.md\`](../replication-2.md) for the method and the status legend.\n\n${[...HEAD, ...rs.map(row)].join('\n')}\n`);
  }
}
process.stdout.write(`${out.join('\n')}\n`);
