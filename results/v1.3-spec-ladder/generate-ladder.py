#!/usr/bin/env python3
"""SO5 spec ladder: derive L1..L4 from each external project's full spec (L5) by deletion only.

Level k = the style's preset, with the first k-1 kinds of project information copied verbatim
from the full spec (results/v1.3-external{,-2}/specs/<id>.yaml, the #133/#181 author). Anything not
yet supplied comes from the preset unchanged. No new judgement is authored at any level.

  L1  style name only      preset `architecture:` and preset `default_exclude_paths` verbatim
  L2  + folder map         each preset layer replaced by the full spec's layer of the same name
  L3  + layer set          the full spec's `layers:` list verbatim (layers added or dropped)
  L4  + exclusion policy   the full spec's `default_exclude_paths` (preset's if the spec has none)
  L5  + DDD declarations   the full spec's `ddd:` block: L5 is the full spec

`fitness_functions`, `allowed_dependencies`, `scoring` and `confidence_thresholds` are the preset's
in every full spec (checked below), so they are identical at every level.

Usage: generate-ladder.py <full-spec-dir> [<full-spec-dir> ...]  (writes specs/L{1..5}/<id>.yaml here)
"""
import copy, glob, json, os, sys
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
PRESETS = {os.path.basename(p)[:-5]: yaml.safe_load(open(p)) for p in glob.glob(os.path.join(REPO, 'presets', '*.yaml'))}
SAME_AS_PRESET = ['fitness_functions', 'scoring', 'confidence_thresholds']


def ladder(full):
    style = full['architecture']['style']
    pre = PRESETS[style]
    fa = full['architecture']
    assert fa.get('allowed_dependencies') == pre['architecture'].get('allowed_dependencies'), 'allowed_dependencies differ'
    for k in SAME_AS_PRESET:
        assert full.get(k) == pre.get(k), k + ' differs from preset'
    assert set(fa) <= {'style', 'layers', 'allowed_dependencies', 'ddd'}, sorted(fa)
    base = {k: copy.deepcopy(v) for k, v in pre.items()}
    base['spec_version'] = full.get('spec_version', pre.get('spec_version'))
    levels = {}
    l1 = copy.deepcopy(base)
    levels['L1'] = l1
    l2 = copy.deepcopy(l1)
    by_name = {l['name']: l for l in fa['layers']}
    l2['architecture']['layers'] = [copy.deepcopy(by_name.get(l['name'], l)) for l in pre['architecture']['layers']]
    levels['L2'] = l2
    l3 = copy.deepcopy(l2)
    l3['architecture']['layers'] = copy.deepcopy(fa['layers'])
    levels['L3'] = l3
    l4 = copy.deepcopy(l3)
    if 'default_exclude_paths' in full:
        l4['default_exclude_paths'] = copy.deepcopy(full['default_exclude_paths'])
    levels['L4'] = l4
    l5 = copy.deepcopy(l4)
    if 'ddd' in fa:
        l5['architecture']['ddd'] = copy.deepcopy(fa['ddd'])
    elif 'ddd' in l5['architecture']:
        del l5['architecture']['ddd']
    levels['L5'] = l5
    # L5 must be the full spec (modulo key order and comments).
    want = {k: v for k, v in full.items()}
    assert json.dumps(l5, sort_keys=True) == json.dumps(want, sort_keys=True), 'L5 != full spec'
    return style, levels


def main(dirs):
    manifest = []
    for d in dirs:
        for f in sorted(glob.glob(os.path.join(d, '*.yaml'))):
            pid = os.path.basename(f)[:-5]
            full = yaml.safe_load(open(f))
            style, levels = ladder(full)
            prev = None
            row = {'id': pid, 'style': style, 'source': os.path.relpath(f, REPO), 'sameAsPrevious': {}}
            for lv, spec in levels.items():
                out = os.path.join(HERE, 'specs', lv, pid + '.yaml')
                os.makedirs(os.path.dirname(out), exist_ok=True)
                head = f'# v1.3 SO5 spec ladder, level {lv}, project `{pid}` (style {style}).\n# Generated by results/v1.3-spec-ladder/generate-ladder.py from {row["source"]}; do not edit.\n'
                with open(out, 'w') as fh:
                    fh.write(head + yaml.safe_dump(spec, sort_keys=False, allow_unicode=True, width=1000))
                key = json.dumps(spec, sort_keys=True)
                if prev is not None:
                    row['sameAsPrevious'][lv] = key == prev
                prev = key
            manifest.append(row)
    with open(os.path.join(HERE, 'specs', 'manifest.json'), 'w') as fh:
        json.dump(manifest, fh, indent=1)
        fh.write('\n')
    print(len(manifest), 'projects x 5 levels written')


if __name__ == '__main__':
    main(sys.argv[1:])
