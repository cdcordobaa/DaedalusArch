#!/usr/bin/env bash
# Regenerates src/cypher-interp/generated/ from Neo4j's official Cypher 25 grammar, as exported by the pinned
# devDependency @neo4j-cypher/language-support (package export "./grammar/*.g4"), with the pinned antlr-ng tool.
# The output is checked in, so neither the grammar package nor the generator is needed at run time; the runtime is
# antlr4ng (pinned in dependencies). Usage, from the repository root: bash scripts/v1.3/gen-cypher-parser.sh
set -euo pipefail
G=node_modules/@neo4j-cypher/language-support/src/antlr-grammar
OUT=src/cypher-interp/generated
rm -rf "$OUT"
mkdir -p "$OUT"
for g in Cypher25Lexer Cypher25Parser; do
  npx antlr-ng -Dlanguage=TypeScript --generate-listener false --lib "$G" -o "$OUT" --exact-output-dir -- "$G/$g.g4"
done
# The grammar's one lexer action is written in Java (RCURLY: `if (!_modeStack.isEmpty()) popMode();`); upstream's own
# CypherCmdLexer.g4 overrides it with the TypeScript equivalent, which is applied here.
sed -i.bak 's/if (!_modeStack.isEmpty()) popMode();/if (this.modeStack.length > 0) this.popMode();/' "$OUT/Cypher25Lexer.ts"
grep -q 'this.modeStack.length > 0' "$OUT/Cypher25Lexer.ts"
rm -f "$OUT"/*.bak "$OUT"/*.interp "$OUT"/*.tokens
for f in "$OUT"/*.ts; do
  { printf '// @ts-nocheck\n/* eslint-disable */\n// Generated by scripts/v1.3/gen-cypher-parser.sh: do not edit.\n'; cat "$f"; } > "$f.tmp" && mv "$f.tmp" "$f"
done
