#!/usr/bin/env bash
# Regenerates src/cypher-interp/generated/ from Neo4j's official Cypher 25 grammar, as exported by the pinned
# devDependency @neo4j-cypher/language-support (package export "./grammar/*.g4"), with the pinned antlr-ng tool.
# The output is checked in, so neither the grammar package nor the generator is needed at run time; the runtime is
# antlr4ng (pinned in dependencies). Usage, from the repository root: bash scripts/v1.3/gen-cypher-parser.sh
#
# Licence: the grammar is Copyright (c) "Neo4j", Neo4j Sweden AB, under the Apache License 2.0. The generated parser
# is a derivative of it, so each generated file keeps the grammar's own copyright and licence header verbatim (copied
# from the .g4, not retyped) followed by an attribution line naming the source and the modification; see NOTICE.
#
# Why a prerelease: @neo4j-cypher/language-support has never published a non-prerelease version. Its `latest` dist-tag
# is 2.0.0-next.6 (2024-05), which ships only the Cypher 5 era CypherParser.g4 and does not export the grammar files;
# the Cypher 25 grammar with the `./grammar/*.g4` export exists only on the `next` line. 2.0.0-next.38 (2026-09-28)
# was the newest `next` when the parser was generated; it is pinned exactly so regeneration is reproducible.
set -euo pipefail
G=node_modules/@neo4j-cypher/language-support/src/antlr-grammar
OUT=src/cypher-interp/generated
rm -rf "$OUT"
mkdir -p "$OUT"
for g in Cypher25Lexer Cypher25Parser; do
  npx antlr-ng -Dlanguage=TypeScript --generate-listener false --lib "$G" -o "$OUT" --exact-output-dir -- "$G/$g.g4"
done
# The grammar's one lexer action is written in Java (RCURLY: `if (!_modeStack.isEmpty()) popMode();`); upstream's own
# CypherCmdLexer.g4 overrides it with the TypeScript equivalent, which is applied here.
sed -i.bak 's/if (!_modeStack.isEmpty()) popMode();/if (this.modeStack.length > 0) this.popMode();/' "$OUT/Cypher25Lexer.ts"
grep -q 'this.modeStack.length > 0' "$OUT/Cypher25Lexer.ts"
rm -f "$OUT"/*.bak "$OUT"/*.interp "$OUT"/*.tokens
VERSION=$(node -p "require('./node_modules/@neo4j-cypher/language-support/package.json').version")
for g in Cypher25Lexer Cypher25Parser; do
  f="$OUT/$g.ts"
  # The grammar's leading /* ... */ copyright block, verbatim.
  header=$(awk 'NR==1 && !/^\/\*/ { exit 1 } { print } /\*\// { exit }' "$G/$g.g4")
  grep -q 'Licensed under the Apache License, Version 2.0' <<<"$header"
  {
    printf '// @ts-nocheck\n/* eslint-disable */\n'
    printf '%s\n' "$header"
    printf '// Generated from %s.g4 of @neo4j-cypher/language-support %s (Neo4j, Apache-2.0) by antlr-ng, with one\n' "$g" "$VERSION"
    printf '// modification: the Java lexer action of RCURLY is replaced by its TypeScript form. See NOTICE.\n'
    printf '// Generated by scripts/v1.3/gen-cypher-parser.sh: do not edit.\n'
    cat "$f"
  } > "$f.tmp" && mv "$f.tmp" "$f"
done
