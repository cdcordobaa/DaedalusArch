/**
 * The author's construct answers: parsing (a plain JSON map or the decision board's database export), writing the
 * switch file (`src/shared/construct-switches.ts`, the generated block) and the list of what the author must sign.
 * Pure apart from `writeSwitchFile`.
 */
import * as fs from 'node:fs';
import type { ConstructAnswers, ConstructSwitch } from '../../../src/shared/construct-switches.js';
import { constructAnswersOf } from '../../../src/shared/construct-switches.js';
import {
  CONSTRUCT_PREVIEW_COMMAND, CONSTRUCT_QUESTION_BY_ID, CONSTRUCT_QUESTION_IDS, CONSTRUCT_QUESTIONS, CONSTRUCT_RERUN_COMMANDS, optionsOf,
} from '../../../src/shared/construct-switch-catalogue.js';
import type { ConstructOption, ConstructOptionKind, ConstructQuestionId } from '../../../src/shared/construct-switch-catalogue.js';

export const SWITCH_FILE = 'src/shared/construct-switches.ts';
const BEGIN = '// BEGIN CONSTRUCT SWITCHES (generated by scripts/v1.3/apply-construct-answers.ts)';
const END = '// END CONSTRUCT SWITCHES';

export interface ParsedAnswers {
  readonly answers: ConstructAnswers;
  readonly answered: ReadonlySet<ConstructQuestionId>;
  readonly notes: Readonly<Partial<Record<ConstructQuestionId, string>>>;
  readonly warnings: readonly string[];
}

/** `Q3`, `q3`, `3`, `Q03`, `Q3.` → `Q3`; undefined when not a question of the page. */
export function questionIdOf(raw: unknown): ConstructQuestionId | undefined {
  if (typeof raw !== 'string' && typeof raw !== 'number') return undefined;
  const m = /^\s*(?:q(?:uestion)?\s*)?0*(\d{1,2})\b/i.exec(String(raw));
  if (m === null) return undefined;
  const id = `Q${String(Number(m[1]))}`;
  return (CONSTRUCT_QUESTION_IDS as readonly string[]).includes(id) ? (id as ConstructQuestionId) : undefined;
}

/** `C`, `c`, `C: advisory in-layer`, `Option C` → `C`; undefined for an empty or unreadable choice. */
export function optionOf(raw: unknown): ConstructOption | undefined {
  if (typeof raw !== 'string') return undefined;
  const m = /^\s*(?:[Oo]ption\s*)?([A-Da-d])(?![A-Za-z])/.exec(raw);
  return m === null ? undefined : (m[1]?.toUpperCase() as ConstructOption);
}

interface Doc { readonly id: unknown; readonly choice: unknown; readonly note: unknown }

function docsOf(doc: unknown): Doc[] {
  const fieldsOf = (d: Record<string, unknown>): Record<string, unknown> => {
    for (const k of ['data', 'fields', 'value', 'doc']) {
      const v = d[k];
      if (v !== null && typeof v === 'object' && !Array.isArray(v)) return { ...d, ...(v as Record<string, unknown>) };
    }
    return d;
  };
  const fromList = (list: readonly unknown[]): Doc[] => list.map((x) => {
    const d = fieldsOf((x ?? {}) as Record<string, unknown>);
    const id = d.doc_id ?? d.docId ?? d.id ?? d._id ?? d.Q ?? d.q ?? d.question ?? d.key;
    return { id, choice: d.choice ?? d.answer ?? d.option, note: d.note };
  });
  if (Array.isArray(doc)) return fromList(doc);
  if (doc === null || typeof doc !== 'object') throw new Error('answers: expected a JSON object or array');
  const o = doc as Record<string, unknown>;
  for (const k of ['documents', 'docs', 'items', 'rows', 'results']) {
    const v = o[k];
    if (Array.isArray(v)) return fromList(v);
  }
  // A plain map: {"Q3": "C"} or {"Q3": {"choice": "C", "note": "..."}}.
  return Object.entries(o).map(([id, v]) => {
    if (v !== null && typeof v === 'object') {
      const d = fieldsOf(v as Record<string, unknown>);
      return { id, choice: d.choice ?? d.answer ?? d.option, note: d.note };
    }
    return { id, choice: v, note: undefined };
  });
}

/** Reads either input format. Throws on an option the question does not offer; unknown keys are warnings. */
export function parseAnswersDocument(doc: unknown): ParsedAnswers {
  const warnings: string[] = [];
  const chosen: { Q: ConstructQuestionId; option: ConstructOption }[] = [];
  const answered = new Set<ConstructQuestionId>();
  const notes: Partial<Record<ConstructQuestionId, string>> = {};
  for (const d of docsOf(doc)) {
    const q = questionIdOf(d.id);
    if (q === undefined) {
      warnings.push(`ignored entry ${JSON.stringify(d.id)}: not a question id Q1..Q25`);
      continue;
    }
    const o = optionOf(d.choice);
    if (typeof d.note === 'string' && d.note.trim() !== '') notes[q] = d.note.trim();
    if (o === undefined) {
      const text = typeof d.choice === 'string' ? d.choice.trim() : JSON.stringify(d.choice ?? null);
      if (text !== '' && text !== 'null') warnings.push(`${q}: unreadable choice ${JSON.stringify(text)}`);
      continue;
    }
    if (!optionsOf(q).includes(o)) throw new Error(`${q} has no option ${o} (options: ${optionsOf(q).join(', ')})`);
    if (answered.has(q)) warnings.push(`${q} answered twice; the last answer (${o}) is used`);
    answered.add(q);
    chosen.push({ Q: q, option: o });
  }
  return { answers: constructAnswersOf(chosen.map((c) => ({ ...c, kinds: {} }))), answered, notes, warnings };
}

export function kindsOf(q: ConstructQuestionId): Partial<Record<ConstructOption, ConstructOptionKind>> {
  const spec = CONSTRUCT_QUESTION_BY_ID.get(q);
  return Object.fromEntries(optionsOf(q).map((o) => [o, spec?.options[o]?.kind ?? 'no-code']));
}

export function switchEntries(answers: ConstructAnswers, notes: Readonly<Partial<Record<ConstructQuestionId, string>>> = {}): ConstructSwitch[] {
  return CONSTRUCT_QUESTION_IDS.map((q) => ({ Q: q, option: answers[q], kinds: kindsOf(q), ...(notes[q] !== undefined ? { note: notes[q] } : {}) }));
}

function entryText(s: ConstructSwitch): string {
  const kinds = Object.entries(s.kinds).map(([o, k]) => `${o}: '${k}'`).join(', ');
  return `  { Q: '${s.Q}', option: '${s.option}', kinds: { ${kinds} }${s.note !== undefined ? `, note: ${JSON.stringify(s.note)}` : ''} },`;
}

/** The generated block of the switch file for these answers. */
export function renderSwitchBlock(answers: ConstructAnswers, notes: Readonly<Partial<Record<ConstructQuestionId, string>>> = {}): string {
  return [BEGIN, 'export const CONSTRUCT_SWITCHES: readonly ConstructSwitch[] = [', ...switchEntries(answers, notes).map(entryText), '];', END].join('\n');
}

/** Replaces the generated block of `text`; throws when the markers are missing. */
export function replaceSwitchBlock(text: string, block: string): string {
  const i = text.indexOf(BEGIN);
  const j = text.indexOf(END);
  if (i < 0 || j < i) throw new Error(`${SWITCH_FILE}: generated block markers not found`);
  return text.slice(0, i) + block + text.slice(j + END.length);
}

export function writeSwitchFile(file: string, answers: ConstructAnswers, notes: Readonly<Partial<Record<ConstructQuestionId, string>>> = {}): void {
  fs.writeFileSync(file, replaceSwitchBlock(fs.readFileSync(file, 'utf8'), renderSwitchBlock(answers, notes)));
}

/** What the author owes for these answers, as printable lines. */
export function signOffLines(parsed: Pick<ParsedAnswers, 'answers' | 'answered'>): string[] {
  const tier: string[] = [];
  const decisions: string[] = [];
  const actions: string[] = [];
  const code: string[] = [];
  const noCode: string[] = [];
  for (const q of CONSTRUCT_QUESTIONS) {
    const o = parsed.answers[q.id];
    const spec = q.options[o];
    const label = `${q.id} ${o}`;
    (spec?.kind === 'code' ? code : noCode).push(label);
    if (!parsed.answered.has(q.id)) continue;
    for (const adr of spec?.adr ?? []) {
      if (adr.kind === 'tier') tier.push(`  ${label}: ${adr.text}`);
      else decisions.push(`  ${label} [${adr.kind}]: ${adr.text}`);
    }
    if (q.actionItem !== undefined) actions.push(`  ${q.id}: ${q.actionItem}`);
  }
  const unanswered = CONSTRUCT_QUESTION_IDS.filter((q) => !parsed.answered.has(q));
  const caveat = (['Q16', 'Q25'] as const).filter((q) => parsed.answers[q] === 'B');
  return [
    'Tier ADRs to write and sign (rule-tiers.md: a tier move needs an ADR with a construct reason; the switch applies an override until then):',
    ...(tier.length > 0 ? tier : ['  none']),
    'ADR-V13-03 "construct decisions" entries:',
    ...(decisions.length > 0 ? decisions : ['  none']),
    'Action items:',
    ...(actions.length > 0 ? actions : ['  none']),
    `Code options in force: ${code.length > 0 ? code.join(', ') : 'none (status quo)'}`,
    `No-code (status quo or confirmation): ${noCode.join(', ')}`,
    ...(unanswered.length > 0 ? [`Unanswered, left at A: ${unanswered.join(', ')}`] : []),
    ...(caveat.length > 0 ? [`${caveat.join(' and ')} B: one development-set run before the hold-out, no second tuning loop; surprises go into an ADR, not code.`] : []),
    'Next:',
    `  offline preview (no Neo4j): ${CONSTRUCT_PREVIEW_COMMAND}`,
    '  development-set re-run (after the ADRs are signed; Neo4j, one run):',
    ...CONSTRUCT_RERUN_COMMANDS.map((c) => `    ${c}`),
  ];
}
