/**
 * MCP v2 consistency check: check_diff's blocking answer against the full evaluation, on every variant of the five
 * v1.3 reference projects, in three tool configurations (`CONSISTENCY_MODES`). Entry file.
 *
 *   npx tsx scripts/v1.3/mcp-consistency.ts [--out results/v1.3-reference/mcp-v2] [--check]
 *
 * Writes consistency.json and consistency.md to --out. `--check` exits 1 when a disagreement is not explained by a
 * documented limit, or when the raw and evidence files of the reference run disagree.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { loadAllReferences } from './lib/reference-model.js';
import { makeTempRoot, materialiseVariant } from './lib/materialise.js';
import {
  blockingDelta,
  compareVariant,
  CONSISTENCY_MODES,
  DOCUMENTED_LIMITS,
  MODE_DESCRIPTIONS,
  projectDiff,
  readFullFindings,
  RESULTS_DIR,
  summarise,
} from './lib/mcp-consistency.js';
import type { ConsistencyMode, VariantComparison } from './lib/mcp-consistency.js';
import { checkDiffTool, createSpecLoader } from '../../src/mcp-server/tools.js';
import type { ServerContext } from '../../src/mcp-server/tools.js';

function context(specPath: string, projectPath: string | undefined): ServerContext {
  return {
    defaultSpecPath: specPath,
    defaultProjectPath: projectPath,
    env: {},
    loadSpec: createSpecLoader(),
    evaluateDeps: {
      makeGraph: () => {
        throw new Error('evaluate_project is not used by the consistency check');
      },
      makePipeline: () => {
        throw new Error('evaluate_project is not used by the consistency check');
      },
    },
  };
}

function markdown(rows: readonly VariantComparison[], problems: readonly string[]): string {
  const { byStyle, byRule } = summarise(rows);
  const out: string[] = [];
  out.push('# MCP v2 consistency: check_diff vs the full evaluation', '');
  out.push(`Generated by \`scripts/v1.3/mcp-consistency.ts\`. Full-evaluation reference: \`${RESULTS_DIR}\` (v1.3 tiers; FF-P06 FLOWS_TO rows N/A; minus the clean variant).`, '');
  out.push('Modes:', '');
  for (const m of CONSISTENCY_MODES) out.push(`- **${m}**: ${MODE_DESCRIPTIONS[m]}`);
  out.push('', '## Agreement per style', '');
  out.push('| Mode | Style | Variants | Blocking answer agrees | Blocking rules agree | Locations agree | Clean/near-miss silent | Unexplained |');
  out.push('|---|---|---|---|---|---|---|---|');
  for (const r of byStyle) out.push(`| ${r.mode} | ${r.style} | ${String(r.variants)} | ${String(r.answerAgree)}/${String(r.variants)} | ${String(r.rulesAgree)}/${String(r.variants)} | ${String(r.locationsAgree)}/${String(r.variants)} | ${r.cleanAndNearMissSilent} | ${String(r.unexplained)} |`);
  out.push('', '## Agreement per rule (variants where the rule blocks)', '');
  out.push('| Mode | Style | Rule | Both | Full only | Tool only |');
  out.push('|---|---|---|---|---|---|');
  for (const r of byRule) out.push(`| ${r.mode} | ${r.style} | ${r.ruleId} | ${String(r.both)} | ${String(r.fullOnly)} | ${String(r.toolOnly)} |`);
  out.push('', '## Disagreements', '');
  const dis = rows.filter((r) => !r.rulesAgree || !r.answerAgrees);
  if (dis.length === 0) out.push('None.');
  else {
    out.push('| Mode | Style | Variant | Full blocking | Tool blocking | Explained by | Unexplained |');
    out.push('|---|---|---|---|---|---|---|');
    for (const r of dis) out.push(`| ${r.mode} | ${r.style} | ${r.variant} | ${r.full.rules.join(', ') || '-'} | ${r.tool.rules.join(', ') || '-'} | ${r.explainedBy.join(', ') || '-'} | ${r.unexplained.join(', ') || '-'} |`);
  }
  out.push('', '## Documented limits', '');
  for (const l of DOCUMENTED_LIMITS) out.push(`- **${l.id}** (${l.modes.join(', ')}; ${l.ruleIds.join(', ')}; ${l.direction}): ${l.reason}`);
  out.push('', '## Location mismatches with agreeing rules', '');
  const loc = rows.filter((r) => r.rulesAgree && !r.locationsAgree);
  if (loc.length === 0) out.push('None.');
  for (const r of loc) out.push(`- ${r.mode} ${r.style}/${r.variant}: full ${r.full.findings.map((f) => `${f.ruleId} ${f.file}`).join('; ')}; tool ${r.tool.findings.map((f) => `${f.ruleId} ${f.file}:${String(f.line)}`).join('; ')}`);
  out.push('', '## Per variant', '');
  out.push('| Mode | Style | Variant | Kind | Full | Tool | Tool advisory | Hints | Basis | ms |');
  out.push('|---|---|---|---|---|---|---|---|---|---|');
  for (const r of rows) out.push(`| ${r.mode} | ${r.style} | ${r.variant} | ${r.kind} | ${r.full.rules.join(', ') || '-'} | ${r.tool.rules.join(', ') || '-'} | ${r.tool.advisoryRules.join(', ') || '-'} | ${r.tool.hints.join(', ') || '-'} | ${r.tool.basis.join(', ')} | ${r.tool.ms.toFixed(0)} |`);
  if (problems.length > 0) {
    out.push('', '## Reference problems', '');
    for (const p of problems) out.push(`- ${p}`);
  }
  return `${out.join('\n')}\n`;
}

async function main(argv: readonly string[]): Promise<number> {
  const repo = process.cwd();
  const outIdx = argv.indexOf('--out');
  const outDir = path.resolve(repo, outIdx >= 0 ? argv[outIdx + 1] ?? '' : 'results/v1.3-reference/mcp-v2');
  const check = argv.includes('--check');
  const tmp = makeTempRoot('mcp-consistency-');
  const rows: VariantComparison[] = [];
  const problems: string[] = [];
  try {
    for (const ref of loadAllReferences(repo)) {
      const cleanVariant = ref.variants.find((v) => v.manifest.variant === 'clean');
      if (cleanVariant === undefined) throw new Error(`${ref.style}: no clean variant`);
      const clean = materialiseVariant(ref, cleanVariant, path.join(tmp, 'clean'));
      const cleanFull = readFullFindings(repo, ref.style, 'clean');
      problems.push(...cleanFull.problems);
      for (const v of ref.variants) {
        const id = v.manifest.variant;
        const m = id === 'clean' ? clean : materialiseVariant(ref, v, path.join(tmp, 'variants'));
        const diff = id === 'clean' ? '' : projectDiff(clean.projectDir, m.projectDir);
        const fullRead = readFullFindings(repo, ref.style, id);
        problems.push(...fullRead.problems);
        const full = id === 'clean' ? blockingDelta(cleanFull.findings, [], ref.style) : blockingDelta(fullRead.findings, cleanFull.findings, ref.style);
        for (const mode of CONSISTENCY_MODES) {
          const root: Record<ConsistencyMode, string | undefined> = { 'after-write': m.projectDir, 'before-write': clean.projectDir, 'spec-only': undefined };
          const ctx = context(ref.specPath, root[mode]);
          const meta = { style: ref.style, variant: id, kind: v.manifest.kind, plants: v.manifest.plants, mode };
          if (id === 'clean') {
            // The clean variant has no diff: the tool's answer is "nothing to check"; the full evaluation must be silent.
            rows.push(compareVariant(meta, full, { verdict: 'clean', summary: '', files: [], skipped: [], blockingVerdict: 'pass', blockingCount: 0, advisoryCount: 0, blockingSummary: '' }, 0));
            continue;
          }
          const t0 = performance.now();
          const res = await checkDiffTool(ctx, { diff });
          const ms = performance.now() - t0;
          if (!res.ok) throw new Error(`${ref.style}/${id} (${mode}): check_diff failed: ${res.message}`);
          rows.push(compareVariant(meta, full, res.data, ms));
        }
      }
    }
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }
  fs.mkdirSync(outDir, { recursive: true });
  const { byStyle, byRule } = summarise(rows);
  fs.writeFileSync(path.join(outDir, 'consistency.json'), `${JSON.stringify({ reference: RESULTS_DIR, modes: MODE_DESCRIPTIONS, limits: DOCUMENTED_LIMITS, byStyle, byRule, problems, rows }, null, 2)}\n`);
  fs.writeFileSync(path.join(outDir, 'consistency.md'), markdown(rows, problems));
  const unexplained = rows.reduce((n, r) => n + r.unexplained.length, 0);
  for (const r of byStyle) process.stdout.write(`${r.mode.padEnd(12)} ${r.style.padEnd(18)} answer ${String(r.answerAgree)}/${String(r.variants)}  rules ${String(r.rulesAgree)}/${String(r.variants)}  locations ${String(r.locationsAgree)}/${String(r.variants)}  silent ${r.cleanAndNearMissSilent}  unexplained ${String(r.unexplained)}\n`);
  process.stdout.write(`wrote ${path.relative(repo, outDir)}/consistency.{json,md}; unexplained disagreements: ${String(unexplained)}; reference problems: ${String(problems.length)}\n`);
  return check && (unexplained > 0 || problems.length > 0) ? 1 : 0;
}

main(process.argv.slice(2)).then(
  (code) => {
    process.exitCode = code;
  },
  (e: unknown) => {
    process.stderr.write(`${e instanceof Error ? e.stack ?? e.message : String(e)}\n`);
    process.exitCode = 2;
  },
);
