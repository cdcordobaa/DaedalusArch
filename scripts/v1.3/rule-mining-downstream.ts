/**
 * Rule mining, live downstream check (Docs/v1.3/rule-mining.md §3): every variant is mined on its own (brownfield) and
 * then evaluated by the firewall (`firewall evaluate --symbolic-only`, Neo4j) under the spec mined from it, and under
 * the true spec for comparison. This shows the emitted specs run on the real engine through the existing templates,
 * and how many planted violations the mined spec reports. Needs Neo4j. Entry file: no exports.
 *
 * `--engine cypher-interp` evaluates with the in-process interpreter (Docs/v1.3/cypher-interpreter.md) instead of
 * Neo4j, with no database and no lock, and writes `downstream-interp*` beside the Neo4j outputs.
 *
 * Usage (repository root):
 *   npx tsx scripts/v1.3/rule-mining-downstream.ts --engine cypher-interp [--out <dir>] [--set ...] [--target ...]
 *   NEO4J_URI=bolt://localhost:7687 NEO4J_PASSWORD=... npx tsx scripts/v1.3/rule-mining-downstream.ts [--out <dir>] [--set dev|heldout|all] [--target id,id]
 *   npx tsx scripts/v1.3/rule-mining-downstream.ts --from-raw [--out <dir>]   (recompute from <out>/downstream-raw)
 * Writes <out>/downstream-raw/<target>/<variant>.json (both specs' rows and the mined spec), <out>/downstream.json and
 * <out>/downstream.md.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { proposeRules } from '../../src/rule-mining/index.js';
import { NodeProcessRunner } from '../../src/shared/process/node-process-runner.js';
import { CLI_ENTRY } from '../lib/freeze-gate-main.js';
import { normaliseFindingPath } from './lib/compare.js';
import { ruleTier } from '../../src/scoring-engine/rule-tiers.js';
import { acquireNeo4jLock } from '../../src/shared/process/neo4j-lock.js';
import type { ActualFinding } from './lib/compare.js';
import { plantedResult } from './lib/ise-compare.js';
import type { PlantedResult } from './lib/ise-compare.js';
import { materialiseTarget, renamedFindings, targetSet, trueSpecText } from './lib/ise-targets.js';
import { makeTempRoot } from './lib/materialise.js';
import { loadAllReferences } from './lib/reference-model.js';
import { LIVE_REFUSAL, liveEvaluator } from './lib/validate-reference-main.js';

interface Raw {
  readonly minedSpec: string;
  readonly minedStyle: string;
  readonly trueFindings: readonly ActualFinding[];
  readonly minedFindings: readonly ActualFinding[];
  readonly minedError?: string;
}

interface Row {
  readonly target: string;
  readonly variant: string;
  readonly kind: string;
  readonly minedError?: string;
  readonly trueSpec: PlantedResult;
  readonly minedSpec: PlantedResult;
  /** Blocking findings under each spec (each spec's own style tiers). */
  readonly blockingTrue: number;
  readonly blockingMined: number;
  /** All findings under the mined spec that name a planted file (brownfield "touched": no clean diff). */
  readonly minedNamesPlantedFile: boolean;
}

const blocking = (fs_: readonly ActualFinding[], style: string): number => fs_.filter((f) => ruleTier(f.ruleId, style).tier === 'blocking').length;

function render(rows: readonly Row[], engine: string): string {
  const out = [`# Rule mining: live downstream (firewall evaluate under the mined spec, engine ${engine})`, '', 'Generated by scripts/v1.3/rule-mining-downstream.ts. Each variant is evaluated under the spec mined from that same variant (brownfield) and under the true spec.', ''];
  out.push('| Target | Variants | Evaluation errors (mined spec) | Planted rule-exact, true spec | Planted rule-exact, mined spec | Expected findings matched, true / mined | Mined spec names the planted file | Clean + near-miss variants with a blocking finding, true / mined |', '|---|---|---|---|---|---|---|---|');
  for (const t of [...new Set(rows.map((r) => r.target))]) {
    const rs = rows.filter((r) => r.target === t);
    const viol = rs.filter((r) => r.kind === 'violation');
    const quiet = rs.filter((r) => r.kind !== 'violation');
    const n = (f: (r: Row) => boolean): number => viol.filter(f).length;
    out.push(`| ${t} | ${String(rs.length)} | ${String(rs.filter((r) => r.minedError !== undefined).length)} | ${String(n((r) => r.trueSpec.plantedDetected === true))}/${String(viol.length)} | ${String(n((r) => r.minedSpec.plantedDetected === true))}/${String(viol.length)} | ${String(viol.reduce((s, r) => s + r.trueSpec.matched, 0))} / ${String(viol.reduce((s, r) => s + r.minedSpec.matched, 0))} of ${String(viol.reduce((s, r) => s + r.trueSpec.expected, 0))} | ${String(n((r) => r.minedNamesPlantedFile))}/${String(viol.length)} | ${String(quiet.filter((r) => r.blockingTrue > 0).length)} / ${String(quiet.filter((r) => r.blockingMined > 0).length)} of ${String(quiet.length)} |`);
  }
  out.push('', '## Per violating variant', '', '| Target | Variant | Plants | True spec | Mined spec | Blocking true / mined |', '|---|---|---|---|---|---|');
  for (const r of rows.filter((x) => x.kind === 'violation')) {
    const f = (p: PlantedResult): string => `${p.plantedDetected === true ? 'detected' : 'missed'} (${String(p.matched)}/${String(p.expected)})`;
    out.push(`| ${r.target} | ${r.variant} | ${r.trueSpec.plants ?? '-'} | ${f(r.trueSpec)} | ${f(r.minedSpec)}${r.minedError !== undefined ? ' ERROR' : ''} | ${String(r.blockingTrue)} / ${String(r.blockingMined)} |`);
  }
  return out.join('\n') + '\n';
}

/** The CLI under `--engine cypher-interp` (no database): the rows `liveEvaluator` returns, from the in-process engine. */
function interpEvaluator(repoRoot: string): (projectDir: string, specPath: string) => Promise<ActualFinding[]> {
  const runner = new NodeProcessRunner();
  const tsx = path.resolve(repoRoot, 'node_modules/.bin/tsx');
  const childEnv: Record<string, string> = {};
  for (const k of ['PATH', 'HOME']) { const v = process.env[k]; if (v !== undefined) childEnv[k] = v; }
  return async (projectDir, specPath) => {
    const r = await runner.run(tsx, [CLI_ENTRY, 'evaluate', '--post-seal', 'off', '--project', projectDir, '--spec', specPath, '--format', 'json', '--symbolic-only', '--engine', 'cypher-interp'], { cwd: repoRoot, env: childEnv, timeoutMs: 600_000 });
    if (!r.success) throw new Error(r.errors.map((e) => e.message).join('; '));
    const start = r.data.stdout.indexOf('{');
    if (start < 0) throw new Error(`no JSON from evaluate: ${r.data.stderr.slice(0, 300)}`);
    const parsed = JSON.parse(r.data.stdout.slice(start)) as { violations?: { functionId: string; filePath: string; target?: string }[] };
    return (parsed.violations ?? []).map((v) => {
      const target = normaliseFindingPath(v.target ?? '', projectDir);
      return { ruleId: v.functionId, file: normaliseFindingPath(v.filePath, projectDir), ...(target !== '' ? { target } : {}) };
    });
  };
}

async function run(): Promise<number> {
  const rawArgv = process.argv.slice(2);
  const ei = rawArgv.indexOf('--engine');
  const engine = ei >= 0 ? rawArgv[ei + 1] ?? '' : 'neo4j';
  if (engine !== 'neo4j' && engine !== 'cypher-interp') { process.stderr.write('--engine must be neo4j or cypher-interp\n'); return 2; }
  const argv = ei >= 0 ? [...rawArgv.slice(0, ei), ...rawArgv.slice(ei + 2)] : rawArgv;
  const tag = engine === 'neo4j' ? 'downstream' : 'downstream-interp';
  const oi = argv.indexOf('--out');
  const ti = argv.indexOf('--target');
  const fromRaw = argv.includes('--from-raw');
  const out = path.resolve(oi >= 0 ? argv[oi + 1] ?? '' : 'results/v1.3-rule-mining/2026-10-16');
  const only = ti >= 0 ? new Set((argv[ti + 1] ?? '').split(',')) : undefined;
  const env = process.env;
  if (!fromRaw && engine === 'neo4j' && ((env.NEO4J_URI ?? '') === '' || (env.NEO4J_PASSWORD ?? '') === '')) {
    process.stderr.write(`${LIVE_REFUSAL}\n`);
    return 2;
  }
  const refs = loadAllReferences(process.cwd());
  const evaluate = fromRaw ? undefined : engine === 'neo4j' ? liveEvaluator(process.cwd(), env) : interpEvaluator(process.cwd());
  const lock = fromRaw || engine !== 'neo4j' ? undefined : await acquireNeo4jLock(env.NEO4J_URI ?? '', { label: 'rule-mining-downstream', env, onWait: (t) => process.stderr.write(`${t}\n`) });
  const work = makeTempRoot('v13-rm-d-');
  const rows: Row[] = [];
  try {
    for (const t of targetSet(argv.includes('--set') ? argv : ['--set', 'dev']).filter((x) => only === undefined || only.has(x.id))) {
      const ref = refs.find((r) => r.style === t.style);
      if (ref === undefined) throw new Error(`no reference ${t.style}`);
      const truePath = path.join(work, `${t.id}.true.yaml`);
      fs.writeFileSync(truePath, trueSpecText(ref, t));
      const scope = new Set(ref.descriptor.scopeRules.map((r) => r.ruleId));
      const raws = new Map<string, Raw>();
      for (const v of ref.variants) {
        const rawFile = path.join(out, `${tag}-raw`, t.id, `${v.manifest.variant}.json`);
        let raw: Raw;
        if (evaluate === undefined) raw = JSON.parse(fs.readFileSync(rawFile, 'utf8')) as Raw;
        else {
          const dir = materialiseTarget(ref, v, t, path.join(work, v.manifest.variant));
          const proposal = await proposeRules(dir, { presetsDir: path.resolve('presets') });
          const minedPath = path.join(work, `${t.id}.${v.manifest.variant}.mined.yaml`);
          fs.writeFileSync(minedPath, proposal.specYaml);
          const trueFindings = await evaluate(dir, truePath);
          try {
            raw = { minedSpec: proposal.specYaml, minedStyle: proposal.style, trueFindings, minedFindings: await evaluate(dir, minedPath) };
          } catch (e: unknown) {
            raw = { minedSpec: proposal.specYaml, minedStyle: proposal.style, trueFindings, minedFindings: [], minedError: e instanceof Error ? e.message : String(e) };
          }
          fs.mkdirSync(path.dirname(rawFile), { recursive: true });
          fs.writeFileSync(rawFile, JSON.stringify(raw, null, 1) + '\n');
        }
        raws.set(v.manifest.variant, raw);
        process.stdout.write(`${t.id}/${v.manifest.variant}: true ${String(raw.trueFindings.length)} rows, mined ${String(raw.minedFindings.length)} rows${raw.minedError !== undefined ? ' ERROR' : ''}\n`);
      }
      const clean = raws.get(ref.variants.find((v) => v.manifest.kind === 'clean')?.manifest.variant ?? '');
      for (const v of ref.variants) {
        const raw = raws.get(v.manifest.variant);
        if (raw === undefined) continue;
        const manifest = { ...v.manifest, expectedFindings: renamedFindings(v.manifest.expectedFindings, t) };
        const files = new Set(manifest.expectedFindings.map((f) => f.file));
        rows.push({
          target: t.id, variant: v.manifest.variant, kind: v.manifest.kind,
          ...(raw.minedError !== undefined ? { minedError: raw.minedError } : {}),
          trueSpec: plantedResult(ref.style, manifest, raw.trueFindings, clean?.trueFindings ?? [], scope),
          minedSpec: plantedResult(ref.style, manifest, raw.minedFindings, clean?.minedFindings ?? [], scope),
          blockingTrue: blocking(raw.trueFindings, ref.style),
          blockingMined: blocking(raw.minedFindings, raw.minedStyle),
          minedNamesPlantedFile: raw.minedFindings.some((f) => [...f.file.split(','), ...(f.target ?? '').split(',')].some((p) => files.has(p.trim()))),
        });
      }
    }
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
    lock?.release();
  }
  fs.writeFileSync(path.join(out, `${tag}.json`), JSON.stringify(rows, null, 1) + '\n');
  fs.writeFileSync(path.join(out, `${tag}.md`), render(rows, engine));
  return 0;
}

void run().then((c) => { process.exitCode = c; }, (e: unknown) => { process.stderr.write(`${e instanceof Error ? e.stack ?? e.message : String(e)}\n`); process.exitCode = 2; });
