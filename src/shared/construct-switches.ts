/** The answers as a lookup; a question missing from the list reads as `A`. */
export type ConstructAnswers = Readonly<Record<ConstructQuestionId, ConstructOption>>;

export function constructAnswersOf(switches: readonly ConstructSwitch[] = CONSTRUCT_SWITCHES): ConstructAnswers {
  const out = Object.fromEntries(CONSTRUCT_QUESTION_IDS.map((q) => [q, 'A'])) as Record<ConstructQuestionId, ConstructOption>;
  for (const s of switches) out[s.Q] = s.option;
  return out;
}

/** Every question at its status quo (option A, or an option the catalogue marks `no-code` with identical behaviour). */
export const STATUS_QUO_ANSWERS: ConstructAnswers = constructAnswersOf([]);

/** Answers with some questions changed (tests and the re-score). */
export function withAnswers(changes: Readonly<Partial<Record<ConstructQuestionId, ConstructOption>>>, base: ConstructAnswers = STATUS_QUO_ANSWERS): ConstructAnswers {
  return { ...base, ...changes };
}

/**
 * True when no answer changes behaviour: every question is at A, or at an option marked `no-code` (Q14 C is the
 * member-fact behaviour already merged, identical to A). Every switch hook is the identity then.
 */
export function isStatusQuo(answers: ConstructAnswers): boolean {
  return CONSTRUCT_QUESTION_IDS.every((q) => answers[q] === 'A' || CONSTRUCT_QUESTION_BY_ID.get(q)?.options[answers[q]]?.kind === 'no-code');
}

/** True when question `q` is answered with `option` (shorthand for the switch hooks). */
export function chose(answers: ConstructAnswers, q: ConstructQuestionId, option: ConstructOption): boolean {
  return answers[q] === option;
}

/** The answers in force: the generated switch file. */
export const CONSTRUCT_ANSWERS: ConstructAnswers = constructAnswersOf();
